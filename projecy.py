import streamlit as st
import pandas as pd

# הגדרת תצורת עמוד
st.set_page_config(page_title="ניתוח דאטה-סט סרטי TMDB", layout="wide")

st.title("🎬 פרויקט 1: הכרות עם הדאטה-סט")
st.subheader("יצירתה של תבונה: בחירות קטנות, השפעות גדולות")

# טעינת הנתונים מקישור ישיר לקובץ CSV (למניעת שגיאת קובץ חסר ב-Streamlit Cloud)
@st.cache_data
def load_data():
    url = "https://raw.githubusercontent.com/algoscale/TMDB-5000-Movies-Analysis/master/tmdb_5000_movies.csv"
    return pd.read_csv(url)

df = load_data()

# לשוניות באפליקציה לפי 3 סעיפי ההנחיה
tab1, tab2, tab3 = st.tabs(["📋 1. הסבר על הדאטה", "🔍 2. מידע על הנתונים", "🎯 3. משתני החיזוי (y, X)"])

# ---------------------------------------------------------
# סעיף 1: הסבר על הדאטה שנבחר (על מה הוא ומה מייצגת כל שורה)
# ---------------------------------------------------------
with tab1:
    st.header("1. הסבר על הדאטה שנבחר")
    st.markdown("""
    הדאטה-סט שנבחר לקוח מספרית TMDB (The Movie Database) והוא מכיל מידע נרחב על כ-5,000 סרטי קולנוע מרחבי העולם.
    כל שורה בטבלה מייצגת **סרט קולנוע יחיד**, והעמודות מקיפות מאפיינים שונים של הסרט: נתונים פיננסיים (תקציב והכנסות קופות),
    מאפייני הפקה (חברות הפקה, מדינות, שפות וז'אנרים), ומדדי אהדת קהל (דירוג ממוצע, מספר מדרגים ומדד פופולריות).
    ניתוח הנתונים נועד להבין את המבנה של עולם הקולנוע לפני שנגש לבניית מודל רגרסיה.
    """)
    st.subheader("תצוגה מקדימה של הנתונים")
    st.dataframe(df.head())

# ---------------------------------------------------------
# סעיף 2: מידע על הנתונים (שורות, עמודות, חסרים וממוצעים)
# ---------------------------------------------------------
with tab2:
    st.header("2. מידע על הנתונים")
    
    col1, col2 = st.columns(2)
    col1.metric("מספר שורות (סרטים)", df.shape[0])
    col2.metric("מספר עמודות (מאפיינים)", df.shape[1])
    
    st.markdown("""
    מבדיקת הערכים החסרים עולה כי העמודות ה"בעייתיות" ביותר הן `homepage` (החסרה בכ-64.46% מהסרטים) ו-`tagline` (החסרה בכ-17.57% מהסרטים). 
    חוסרים אלו הגיוניים כיוון שלא לכל סרט יש אתר אינטרנט רשמי או סלוגן שיווקי. מכיוון שמדובר בעמודות טקסטואליות בלבד, היעדרן לא יפגע בחיזוי המספרי בהמשך. 
    בעמודות המספריות החוסרים מזעריים (2 שורות בלבד בעמודת `runtime`), וניתן יהיה לטפל בהם בקלות.
    
    מבחינת המדדים הסטטיסטיים, ממוצע התקציב (`budget`) עומד על כ-29.04 מיליון דולר וממוצע ההכנסות (`revenue`) עומד על כ-82.26 מיליון דולר. 
    נתונים אלו הגיוניים לתעשיית הקולנוע ההוליוודית, אך מראים שהתפלגות ההכנסות מיושרת ימינה – מעט סרטי ענק (Blockbusters) מרוויחים סכומי שיא ומעלים את הממוצע, 
    בעוד שרבים מהסרטים מרוויחים סכומים צנועים יותר. ממוצע אורך הסרט (`runtime`) הוא כ-106.88 דקות, נתון הגיוני המשקף אורך מקובל של סרט קולנוע.
    """)
    
    col_a, col_b = st.columns(2)
    with col_a:
        st.subheader("ערכים חסרים")
        missing = df.isnull().sum()
        missing_df = pd.DataFrame({
            'ערכים חסרים': missing,
            'אחוז חסר (%)': (missing / len(df) * 100).round(2)
        })
        st.dataframe(missing_df[missing_df['ערכים חסרים'] > 0])
        
    with col_b:
        st.subheader("מדדים מספריים (ממוצעים)")
        numeric_cols = ['budget', 'revenue', 'runtime', 'popularity', 'vote_average']
        st.dataframe(df[numeric_cols].describe().round(2))

# ---------------------------------------------------------
# סעיף 3: מה נרצה לחזות (y) ובאמצעות אילו עמודות (X) + נימוקים
# ---------------------------------------------------------
with tab3:
    st.header("3. הגדרת משתני החיזוי והנימוקים")
    
    st.success("🎯 **עמודת החיזוי (y):** `revenue` - הכנסות הסרט בקופות בדולרים (משתנה מספרי רציף המהווה מדד מרכזי להצלחה מסחרית).")
    
    st.markdown("""
    ### משתנים לחיזוי (X) ונימוקים:
    1. **`budget` (תקציב):** תקציב הפקה גבוה מאפשר להשקיע באפקטים ויזואליים, בשחקנים מובילים ובקמפיינים שיווקיים רחבים, אשר משפיעים ישירות על נכונות הקהל לרכוש כרטיסים.
    2. **`popularity` (מדד פופולריות):** מדד המציג את רמת העניין, החיפושים והציפייה של הקהל לקראת הסרט.
    3. **`runtime` (אורך הסרט בדקות):** אורך הסרט משפיע על מספר ההקרנות ביום שבית הקולנוע יכול לשבץ, וכן על תפיסת הצופה לגבי ערך הסרט.

    ---
    ⚠️ **מניעת Data Leakage (זליגת מידע):**
    נמנענו מלהשתמש בעמודה `vote_count` (מספר המדרגים) כמנבא. אף על פי שיש לה מתאם חזק להכנסות, מספר המדרגים נצבר ונודע רק *לאחר* שהסרט כבר הופץ והקרנותיו הסתיימו. 
    המשתנים שנבחרו (`budget`, `runtime`, ו-`popularity`) ידועים או מוערכים עוד בטרם יציאת הסרט לאקרנים.
    """)
